/// G02 — Your coaching · your support. Step 3 of 3.
///
/// Matches `6-v2/src/screens-coached.mjs` → `G02`. Its design note names what
/// the screen is for:
///
/// > The third step separates two consents that most apps merge: coaching sees
/// > her training and food, and cycle information stays hers unless she
/// > switches it on.
///
/// ## Three switches, and no fourth that moves them
///
/// Each row is one independent boolean, **off by default**, and there is no
/// "share everything" control on this screen because there is none in the type
/// (`domain/sharing.dart`). A master switch is the one control HANDOFF rule 6
/// forbids, and the reason it is forbidden is that consent given in one tap is
/// consent nobody read.
///
/// ## The honest offline wording
///
/// `P0-SHARE-03` asserts that the copy "does NOT say immediately". When a flip
/// has not reached the server, [syncNotice] renders the dictionary's
/// "Saved here until you have signal" — because a server cannot deny a read it
/// has not been told about, and telling her otherwise would be a promise the
/// system cannot keep. The dictionary contains no string saying "immediately"
/// at all, which is asserted by test.
library;

import 'package:flutter/material.dart';

import '../../../l10n/app_l10n.dart';
import '../../../theme/app_tokens.dart';
import '../../../ui/app_button.dart';
import '../../../ui/app_card.dart';
import '../../../ui/app_field.dart';
import '../../../ui/app_scaffold.dart';
import '../../../ui/app_segmented.dart';
import '../../../ui/app_toggle.dart';
import '../domain/sharing.dart';
import '../../../ui/hand/hand_seed_name.dart';

class CoachingSupportView extends StatelessWidget {
  const CoachingSupportView({
    super.key,
    this.onBack,
    this.onSend,
    this.onPreviewSharing,
    this.onToggleSharing,
    this.onDailyCheckin,
    this.switches = SharingSwitches.off,
    this.dailyCheckin = true,
    this.syncState,
    this.reminderTime,
  });

  final VoidCallback? onBack;
  final VoidCallback? onSend;

  /// "See exactly what she would see" — the preview is generated by the same
  /// projector that builds the real projection, or the preview lies.
  final VoidCallback? onPreviewSharing;

  final void Function(SharingKey key, bool value)? onToggleSharing;
  final ValueChanged<bool>? onDailyCheckin;

  /// All four default false. The three cycle switches are the rows below; the
  /// `logs` switch is the app-level one and lives in Privacy, not here.
  final SharingSwitches switches;

  final bool dailyCheckin;

  /// Set when a flip has been saved on the handset but not yet synced.
  final SharingSyncState? syncState;

  final String? reminderTime;

  @override
  Widget build(BuildContext context) {
    final l10n = AppL10n.of(context);

    return AppScaffold(
      appBar: AppTopBar(title: l10n.yourCoaching, onBack: onBack),
      footer: [AppButton(l10n.sendToSara, icon: Icons.send, onPressed: onSend)],
      children: [
        AppSegmented(
          items: [l10n.yourTraining, l10n.yourFood, l10n.yourSupport],
          selectedIndex: 2,
        ),
        Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(l10n.yourSupport, style: AppText.titleM),
            const SizedBox(height: 3),
            Text(
              l10n.step3Of3,
              style: AppText.bodyM.copyWith(color: AppColors.onSurfaceVariant),
            ),
          ],
        ),
        AppField(
          label: l10n.reminderTime,
          // "7:30 in the morning" sat in this field as though she had chosen
          // it. An empty field is the honest rendering of a time she has not
          // set yet.
          hint: reminderTime ?? '',
          trailing: const Icon(
            Icons.schedule,
            size: 22,
            color: AppColors.primaryDim,
          ),
        ),
        AppCard(
          padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 12),
          children: [
            Row(
              children: [
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(l10n.dailyCheckIn, style: AppText.titleM),
                      const SizedBox(height: 2),
                      Text(
                        l10n.oneShortSheetItDoesNotMean,
                        style: AppText.bodyM.copyWith(
                          color: AppColors.onSurfaceVariant,
                        ),
                      ),
                    ],
                  ),
                ),
                const SizedBox(width: 12),
                AppToggle(
                  value: dailyCheckin,
                  onChanged: onDailyCheckin,
                  semanticLabel: l10n.dailyCheckIn,
                ),
              ],
            ),
          ],
        ),
        AppCard(
          variant: AppCardVariant.sage,
          gap: 10,
          children: [
            Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(l10n.shareCycleInformationWithSara, style: AppText.titleM),
                const SizedBox(height: 3),
                Text(
                  l10n.offUnlessYouTurnItOnCoaching,
                  style: AppText.bodyM.copyWith(
                    color: AppColors.onSurfaceVariant,
                  ),
                ),
              ],
            ),
            _SwitchRow(
              label: l10n.energyAndAppetite,
              value: switches.energyAppetite,
              onChanged: onToggleSharing == null
                  ? null
                  : (v) => onToggleSharing!(SharingKey.energyAppetite, v),
            ),
            _SwitchRow(
              label: l10n.cycleSymptoms,
              value: switches.symptoms,
              onChanged: onToggleSharing == null
                  ? null
                  : (v) => onToggleSharing!(SharingKey.symptoms, v),
            ),
            _SwitchRow(
              label: l10n.periodDatesAndPatterns,
              value: switches.datesAndPatterns,
              onChanged: onToggleSharing == null
                  ? null
                  : (v) => onToggleSharing!(SharingKey.datesAndPatterns, v),
            ),
            // The preview must come from the same projector as the real
            // projection, or "exactly what she would see" is a label.
            AppButton(
              l10n.seeExactlyWhatSheWouldSee,
              variant: AppButtonVariant.text,
              height: 40,
              fontSize: 15,
              onPressed: onPreviewSharing,
            ),
          ],
        ),
        if (syncState == SharingSyncState.savedOnDevice)
          Row(
            children: [
              const Icon(
                Icons.cloud_queue,
                size: 16,
                color: AppColors.onSurfaceVariant,
              ),
              const SizedBox(width: 6),
              Expanded(
                child: Text(
                  // Never "immediately": the server has not heard yet.
                  l10n.savedHereUntilYouHaveSignal,
                  style: AppText.bodyM.copyWith(
                    color: AppColors.onSurfaceVariant,
                  ),
                ),
              ),
            ],
          ),
        Text(
          l10n.yourWorkoutResultsAndTheMealsYou,
          style: AppText.bodyM.copyWith(color: AppColors.onSurfaceVariant),
        ),
      ],
    );
  }
}

/// One sharing row: a label and its own switch, and nothing that reaches
/// another row.
class _SwitchRow extends StatelessWidget implements HandSeedName {
  @override
  String get handSeedName => '_SwitchRow';

  const _SwitchRow({required this.label, required this.value, this.onChanged});

  final String label;
  final bool value;
  final ValueChanged<bool>? onChanged;

  @override
  Widget build(BuildContext context) {
    return Row(
      children: [
        Expanded(child: Text(label, style: AppText.body)),
        const SizedBox(width: 12),
        AppToggle(value: value, onChanged: onChanged, semanticLabel: label),
      ],
    );
  }
}
